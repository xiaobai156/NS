    [Theory]
    [InlineData("新澳六合彩资料", "狗庄", "01 02 04 20 21 26 27 28 31 35 43", "49", "01 02 04 20 21 26 27 28 31 35 43 49")]
    [InlineData("新澳六合彩资料", "天线宝杀", "12码→11 15 26 28 31 34 41 43 44 45 46", "48←精选杀", "11 15 26 28 31 34 41 43 44 45 46 48")]
    public void ReadsANonFirstRowAndIgnoresBrokenOlderRows(string group, string id, string first, string last, string expected)
    {
        string[] lines = ["249期缺失", first, "248期兔40中", last, "乱码123", "247期牛30中"];
        Assert.Equal(expected, RuleEngine.ExtractFinalValue(lines, 248, LoadRule(group, id)));
    }

    [Fact]
    public void NewWrappedRowHandlingDoesNotApplyToOtherRules()
    {
        string[] lines = ["0412151827293039434546", "248期开??", "48", "14153639", "247期兔40中"];
        Assert.Null(RuleEngine.ExtractFinalValue(lines, 248, new OcrRule("其他", "号码:12", StrictIssueBlock: true)));
    }

