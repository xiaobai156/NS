    [Fact]
    public void LeifengTemplateMatchesTheRealTitle()
    {
        VisualTemplateSet catalog = VisualTemplateMatcher.Load(Path.Combine(
            ResultFilePaths.ConfigurationDirectory(AppContext.BaseDirectory), "新澳六合彩资料.templates.json"));
        string image = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "Fixtures", "leifeng.jpg"));
        VisualTemplateMatch match = Assert.Single(VisualTemplateMatcher.Match([image], catalog));
        Assert.Equal("雷锋", match.Template.Id);
        Assert.InRange(match.Distance, 0, catalog.MaxDistance);
    }

    private static OcrRule LoadRule(string group, string id) => RuleCatalog.Load(
        Path.Combine(ResultFilePaths.ConfigurationDirectory(AppContext.BaseDirectory), group + ".json"))
        .Single(rule => rule.Id == id);

    [Theory]
    [MemberData(nameof(Samples))]
    public void ExtractsConfirmedValueUsingActualConfiguration(
        string group, string id, string[] lines, string expected)
    {
        OcrRule rule = LoadRule(group, id);
        foreach (int issue in new[] { 248, 301, 1001 })
        {
            string[] shifted = lines.Select(line => Regex.Replace(line, @"\d+(?=期)",
                match => (int.Parse(match.Value) + issue - 248).ToString())).ToArray();
            Assert.Equal(expected, RuleEngine.ExtractFinalValue(shifted, issue, rule));
            Assert.Null(RuleEngine.ExtractFinalValue(shifted, issue + 1, rule));
        }
    }

    [Theory]
    [MemberData(nameof(InvalidRows))]
    public void RejectsIncompleteConflictingOrCrossIssueRows(string group, string id, string[] lines)
    {
        Assert.Null(RuleEngine.ExtractFinalValue(lines, 248, LoadRule(group, id)));
    }

